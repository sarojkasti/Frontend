import * as XLSX from "xlsx";
import dayjs from "dayjs";
import { ReportColumnConfig } from "../types/reportTypes";

export interface ExportMetadata {
  reportTitle: string;
  dateRangeText: string;
  filterSummaryText?: string;
  generatedBy?: string;
}

export const exportReportToExcel = (
  metadata: ExportMetadata,
  columns: ReportColumnConfig[],
  data: any[],
  summaryRow?: Record<string, any>
) => {
  const visibleColumns = columns.filter((col) => col.key !== "action");

  // Build rows array for AoA (Array of Arrays)
  const rows: any[][] = [];

  // 1. Report Header Section
  rows.push(["ARTHA ENTERPRISE MANAGEMENT SYSTEM"]);
  rows.push([metadata.reportTitle.toUpperCase()]);
  rows.push([`Date Range: ${metadata.dateRangeText}`]);
  if (metadata.filterSummaryText) {
    rows.push([`Applied Filters: ${metadata.filterSummaryText}`]);
  }
  rows.push([
    `Generated On: ${dayjs().format("YYYY-MM-DD hh:mm A")} | Generated By: ${metadata.generatedBy || "Authorized User"}`,
  ]);
  rows.push([]); // Empty spacer row

  // 2. Table Column Headers
  const headerTitles = visibleColumns.map((col) => col.title);
  rows.push(headerTitles);

  // 3. Data Rows
  data.forEach((row, idx) => {
    const rowValues = visibleColumns.map((col) => {
      if (col.key === "sn" || col.key === "sno" || col.key === "index") {
        return idx + 1;
      }
      const val = col.dataIndex ? row[col.dataIndex] : row[col.key];
      if (val === null || val === undefined) return "-";
      if (typeof val === "boolean") return val ? "Yes" : "No";
      if (typeof val === "number") return val;
      return String(val);
    });
    rows.push(rowValues);
  });

  // 4. Summary Totals Row (if provided)
  if (summaryRow) {
    const summaryValues = visibleColumns.map((col) => {
      if (col.key === "sn" || col.key === "sno" || col.key === "index") {
        return "TOTAL";
      }
      const val = summaryRow[col.key] || summaryRow[col.dataIndex || ""];
      if (val !== undefined && val !== null) return val;
      return "";
    });
    rows.push(summaryValues);
  }

  // Create worksheet
  const worksheet = XLSX.utils.aoa_to_sheet(rows);

  // Auto-fit column widths
  const colWidths = visibleColumns.map((col, cIdx) => {
    let maxLen = col.title.length;
    data.forEach((row) => {
      const val = col.dataIndex ? row[col.dataIndex] : row[col.key];
      if (val !== null && val !== undefined) {
        const str = String(val);
        if (str.length > maxLen) maxLen = str.length;
      }
    });
    return { wch: Math.min(Math.max(maxLen + 4, 12), 40) };
  });
  worksheet["!cols"] = colWidths;

  // Create workbook
  const workbook = XLSX.utils.book_new();
  const safeSheetName = metadata.reportTitle.slice(0, 31).replace(/[\\/?*[\]]/g, "_");
  XLSX.utils.book_append_sheet(workbook, worksheet, safeSheetName || "Report Sheet");

  // Filename
  const fileName = `${metadata.reportTitle.replace(/\s+/g, "_")}_${dayjs().format("YYYYMMDD_HHmm")}.xlsx`;
  XLSX.writeFile(workbook, fileName);
};

export const exportReportToCsv = (
  metadata: ExportMetadata,
  columns: ReportColumnConfig[],
  data: any[]
) => {
  const visibleColumns = columns.filter((col) => col.key !== "action");
  const headers = visibleColumns.map((col) => `"${col.title.replace(/"/g, '""')}"`);

  const rows = data.map((row, idx) => {
    return visibleColumns
      .map((col) => {
        let val: any;
        if (col.key === "sn" || col.key === "sno" || col.key === "index") {
          val = idx + 1;
        } else {
          val = col.dataIndex ? row[col.dataIndex] : row[col.key];
        }
        if (val === null || val === undefined) val = "";
        const str = String(val).replace(/"/g, '""');
        return `"${str}"`;
      })
      .join(",");
  });

  const csvContent = "\uFEFF" + [headers.join(","), ...rows].join("\r\n");
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute(
    "download",
    `${metadata.reportTitle.replace(/\s+/g, "_")}_${dayjs().format("YYYYMMDD_HHmm")}.csv`
  );
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};

